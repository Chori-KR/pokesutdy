def tide(level, label):
    """바닷가 단면: level(물 높이 y, 작을수록 높음). 왼쪽 땅 비탈, 오른쪽 바다"""
    xi = 20 + (level - 30) * 2
    out = [f'<polygon points="{_n_(xi)},{level} 150,{level} 150,90 140,90" fill="{BLUE}" fill-opacity="0.35"/>',
           f'<line x1="{_n_(xi)}" y1="{level}" x2="150" y2="{level}" stroke="{BLUE}" stroke-width="3"/>',
           f'<polygon points="20,30 140,90 150,90 150,102 10,102 10,30" fill="{ORANGE}" fill-opacity="0.3" stroke="{C}" stroke-width="2.5" stroke-linejoin="round"/>',
           ]
    return svg(160, 108, "".join(out))


def _earth():
    inner = pie(10, 7).split(">", 1)[1].rsplit("</svg>", 1)[0]
    body = (f'<g transform="translate(6,4) scale(0.95)">{inner}</g>'
            f'<rect x="150" y="30" width="16" height="16" fill="{BLUE}" fill-opacity="0.45" stroke="{C}" stroke-width="2"/>' + text(172, 43, "바다", 14, "start", "bold")
            + f'<rect x="150" y="62" width="16" height="16" fill="none" stroke="{C}" stroke-width="2"/>' + text(172, 75, "육지", 14, "start", "bold"))
    return svg(230, 92, body)


