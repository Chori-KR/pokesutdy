def micro_paramecium():
    """짚신벌레: 길쭉한 몸 + 가장자리 털"""
    out = [f'<ellipse cx="60" cy="42" rx="40" ry="18" fill="{BLUE}" fill-opacity="0.3" stroke="{C}" stroke-width="2.5"/>']
    for k in range(10):
        x = 28 + k * 7
        out.append(line(x, 24, x - 2, 17, 2) + line(x, 60, x - 2, 67, 2))
    out.append(f'<circle cx="52" cy="42" r="5" fill="none" stroke="{C}" stroke-width="2"/>')
    return svg(120, 84, "".join(out))


def micro_bacteria():
    """세균: 아주 작은 막대와 공 모양 여러 개"""
