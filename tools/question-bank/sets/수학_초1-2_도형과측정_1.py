def cups(levels, names, shape_="same"):
    """같은 모양 그릇의 물 높이(0~1)"""
    o = []
    for i, (lv, nm) in enumerate(zip(levels, names)):
        x = 20 + i * 90
        top, bot = 20, 130
        hgt = (bot - top) * lv
        o.append(f'<rect x="{x + 3}" y="{_n(bot - hgt)}" width="54" height="{_n(hgt)}" fill="{BLUE}" fill-opacity="0.4"/>')
        for k in range(int(hgt // 12)):
            o.append(line(x + 10, bot - 6 - k * 12, x + 50, bot - 6 - k * 12, 2, 0.35))
        o.append(f'<polyline points="{x},{top} {x},{bot} {x + 60},{bot} {x + 60},{top}" fill="none" {ST}/>')
        o.append(text(x + 30, bot + 22, nm, 15, weight="bold"))
    return svg(len(levels) * 90 + 10, 160, "".join(o))


def grid_figs(figs, cols, rows, s=24):
    """모눈 위의 도형: figs=[(칸 목록, 이름)] 칸은 (c, r)"""
    o = []
    W, H = cols * s + 8, rows * s + 8
    for c in range(cols + 1):
        o.append(line(4 + c * s, 4, 4 + c * s, 4 + rows * s, 2, 0.25))
    for r in range(rows + 1):
        o.append(line(4, 4 + r * s, 4 + cols * s, 4 + r * s, 2, 0.25))
    for k, (cells, name) in enumerate(figs):
        col = BLUE if k % 2 == 0 else ORANGE
        for (c, r) in cells:
            o.append(f'<rect x="{4 + c * s}" y="{4 + r * s}" width="{s}" height="{s}" fill="{col}" fill-opacity="0.45" stroke="{C}" stroke-width="2"/>')
        mx = sum(c for c, _ in cells) / len(cells)
        my = sum(r for _, r in cells) / len(cells)
        cx, cy = min(cells, key=lambda t: (t[0] - mx) ** 2 + (t[1] - my) ** 2)
        o.append(text(4 + (cx + 0.5) * s, 4 + (cy + 0.5) * s + 5, name, 15, weight="bold"))
    return svg(W, H, "".join(o))


def rect_cells(c0, r0, w, h):
    return [(c0 + i, r0 + j) for i in range(w) for j in range(h)]


