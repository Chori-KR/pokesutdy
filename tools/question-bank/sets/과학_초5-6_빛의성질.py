def mirror_simple(W=250):
    """평면거울에 비춘 손전등 빛이 부딪혀 방향이 바뀌는 모습 (법선·각도 표시 없음)"""
    from kit_sci56 import _arrow
    my = 120
    out = [line(30, my, W - 30, my, 4)]
    for k in range(0, 8):
        x = 40 + k * 25
        out.append(line(x, my + 2, x - 10, my + 14, 2, op=0.6))
    out.append(text(W - 30, my + 30, "거울", 12, anchor="end"))
    out.append(_arrow(50, 30, 125, my, 2.5, ORANGE))
    out.append(_arrow(125, my, 200, 30, 2.5, ORANGE))
    out.append(text(46, 24, "손전등 빛", 12, anchor="start"))
    return svg(W, my + 40, "".join(out))


