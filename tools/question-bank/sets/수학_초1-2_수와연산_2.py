X = "\\times"


def m(a, b_, c=None):
    """곱셈식 LaTeX: $a \\times b$ 또는 $a \\times b = c$"""
    return f"${a} {X} {b_}$" if c is None else f"${a} {X} {b_} = {c}$"


def box_and_beads(outside, r=11):
    """상자(속이 안 보임) + 밖에 있는 구슬"""
    out = [f'<rect x="10" y="10" width="90" height="70" rx="8" fill="{ORANGE}" fill-opacity="0.35" stroke="{C}" stroke-width="2.5"/>',
           text(55, 52, "?개", 18, weight="bold"), text(55, 100, "상자 속", 13, weight="bold")]
    for i in range(outside):
        out.append(shape("circle", 130 + (i % 4) * 28, 30 + (i // 4) * 28, r, fill=BLUE))
    out.append(text(130 + 1.5 * 28, 100, "상자 밖", 13, weight="bold"))
    return svg(250, 108, "".join(out))


def array(rows, cols, r=10):
    cs = 2 * r + 8
    out = [shape("circle", 12 + r + c * cs, 12 + r + rr * cs, r, fill=BLUE) for rr in range(rows) for c in range(cols)]
    return svg(cols * cs + 18, rows * cs + 18, "".join(out))


def times_table(rs, cs, hide):
    head = ["×"] + [str(c) for c in cs]
    rows = [[str(r)] + ["?" if (r, c) == hide else str(r * c) for c in cs] for r in rs]
    return table(head, rows, col_w=56, first_w=56)


