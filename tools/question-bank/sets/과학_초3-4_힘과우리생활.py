def slope(h, L, label=None):
    """빗면: 높이 h, 길이 L. 위에 상자"""
    x0, y0 = 14, 100
    out = [f'<polygon points="{x0},{y0} {x0 + L},{y0} {x0 + L},{y0 - h}" fill="{ORANGE}" fill-opacity="0.3" stroke="{C}" stroke-width="2.5" stroke-linejoin="round"/>',
           f'<rect x="{x0 + L - 18}" y="{y0 - h - 14}" width="18" height="14" fill="none" stroke="{C}" stroke-width="2.5"/>']
    if label:
        out.append(text(x0 + L / 2, y0 + 18, label, 13, weight="bold"))
    return svg(x0 + L + 14, 122, "".join(out))


