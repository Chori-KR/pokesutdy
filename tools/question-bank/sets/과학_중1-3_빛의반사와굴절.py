def ray(inc, ref, kind="refract"):
    """공기(위)-물(아래) 경계에서 입사·굴절(또는 반사) 광선"""
    W, H = 230, 190
    cx, cy = 115, 95
    L = 70
    s = math.sin
    c = math.cos
    out = [line(20, cy, 210, cy, 2.5), line(cx, 20, cx, 170, 1.8, dash="5 4"),
           text(34, cy - 8, "공기", 13, "start"), text(34, cy + 18, "물", 13, "start"), text(cx + 6, 28, "법선", 12, "start")]
    ix, iy = cx - L * s(math.radians(inc)), cy - L * c(math.radians(inc))
    out.append(line(ix, iy, cx, cy, 3, color=BLUE))
    if kind == "refract":
        ex, ey = cx + L * s(math.radians(ref)), cy + L * c(math.radians(ref))
    else:
        ex, ey = cx + L * s(math.radians(ref)), cy - L * c(math.radians(ref))
    out.append(line(cx, cy, ex, ey, 3, color=ORANGE))
    out.append(text(ix - 6, iy - 6, "입사 광선", 12, "end"))
    out.append(text(ex + 6, ey + (14 if kind == "refract" else -6), "굴절 광선" if kind == "refract" else "반사 광선", 12, "start"))
    return svg(W, H, "".join(out))


