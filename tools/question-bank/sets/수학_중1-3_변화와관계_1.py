def widen(s_, dx=14):
    """세 자리 눈금 숫자가 왼쪽에서 잘리지 않게 viewBox를 왼쪽으로 넓힘"""
    import re
    return re.sub(r'viewBox="0 0 (\d+) (\d+)"', lambda m: f'viewBox="-{dx} 0 {int(m.group(1)) + dx} {m.group(2)}"', s_, count=1)


