def congv(k):
    """합동인 직각삼각형 두 개 (대응: ㄱ→ㄹ, ㄴ→ㅁ, ㄷ→ㅂ). k마다 크기·배치가 다르다"""
    a, b_ = [(60, 40), (70, 44), (54, 50), (66, 36), (58, 46), (72, 40)][k % 6]
    P1 = [(0, 0), (a, 0), (0, b_)]
    if k % 2 == 0:   # 돌려서 놓기
        P2 = [(a + 40, b_ + 10), (40, b_ + 10), (a + 40, 10)]
    else:            # 뒤집어서 놓기
        P2 = [(2 * a + 40, 0), (a + 40, 0), (2 * a + 40, b_)]
    return cong_pair(P1, P2, ["ㄱ", "ㄴ", "ㄷ"], ["ㄹ", "ㅁ", "ㅂ"])

