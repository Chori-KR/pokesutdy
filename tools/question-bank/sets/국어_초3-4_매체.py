def search_screen(query, results):
    """검색창과 검색 결과 목록 (제목, 출처)"""
    W = 320
    out = [f'<rect x="4" y="4" width="{W - 8}" height="38" rx="19" fill="none" {ST}/>',
           f'<circle cx="25" cy="21" r="7" fill="none" stroke="{C}" stroke-width="2.5"/>', line(30, 26, 36, 32, 2.5),
           text(52, 29, query, 14, "start", "bold")]
    y = 54
    for title, src in results:
        out.append(f'<rect x="4" y="{y}" width="{W - 8}" height="52" rx="8" fill="none" stroke="{C}" stroke-width="2"/>')
        out.append(text(16, y + 22, title, 13, "start", "bold"))
        out.append(text(16, y + 42, src, 12, "start"))
        y += 60
    return svg(W, y + 2, "".join(out))


def slide(title, bullets, pic=True, tsize=16, bsize=13):
    """발표 자료 한 쪽"""
    W, H = 280, 170
    out = [f'<rect x="4" y="4" width="{W - 8}" height="{H - 8}" rx="8" fill="none" {ST}/>',
           text(W / 2, 30, title, tsize, weight="bold")]
    y = 54
    for bl in bullets:
        out.append(text(16, y, bl, bsize, "start"))
        y += bsize + 5
    if pic:
        out.append(f'<rect x="170" y="48" width="96" height="100" fill="{BLUE}" fill-opacity="0.25" stroke="{C}" stroke-width="2"/>')
        out.append(line(170, 48, 266, 148, 2, 0.5) + line(266, 48, 170, 148, 2, 0.5))
        out.append(text(218, 102, "사진", 13, weight="bold"))
    return svg(W, H, "".join(out))


def mini_slide(title, bullets, pic=False):
    """작은 발표 자료 한 쪽 (네 개를 두 줄로 늘어놓을 때)"""
    W, H = 200, 150
    out = [f'<rect x="3" y="3" width="{W - 6}" height="{H - 6}" rx="8" fill="none" {ST}/>',
           text(W / 2, 28, title, 15, weight="bold")]
    y = 52
    for bl in bullets:
        out.append(text(12, y, bl, 13, "start"))
        y += 18
    if pic:
        out.append(f'<rect x="104" y="44" width="84" height="92" fill="{BLUE}" fill-opacity="0.25" stroke="{C}" stroke-width="2"/>')
