def two_groups(n1, n2, k1="circle", k2="square", lab1="", lab2="", r=11):
    """두 무리(모양을 달리해 구분) + 이름"""
    cs = 2 * r + 8
    out = []
    x = 10
    for n, k, lab, col in ((n1, k1, lab1, BLUE), (n2, k2, lab2, ORANGE)):
        cols = min(n, 5)
        rows = (n - 1) // 5 + 1
        w = cols * cs + 8
        out.append(f'<rect x="{x}" y="6" width="{w}" height="{rows * cs + 10}" rx="8" fill="none" stroke="{C}" stroke-width="2" stroke-dasharray="5 4"/>')
        for i in range(n):
            out.append(shape(k, x + 4 + r + 4 + (i % 5) * cs, 11 + r + 4 + (i // 5) * cs, r, fill=col))
        if lab:
            out.append(text(x + w / 2, rows * cs + 36, lab, 13, weight="bold"))
        x += w + 18
    H = max((n1 - 1) // 5 + 1, (n2 - 1) // 5 + 1) * (2 * r + 8) + 44
    return svg(x - 8, H, "".join(out))


def place_table(digits):
    return table(["천의 자리", "백의 자리", "십의 자리", "일의 자리"], [[str(d) for d in digits]], col_w=78, first_w=78)


