def court(players, ball=None, W=230, H=140):
    """코트 그림: players [(이름, x, y, 'a'|'d')] 0~1 비율. a=우리 팀(원), d=상대 팀(네모)"""
    out = [f'<rect x="6" y="6" width="{W - 12}" height="{H - 12}" rx="4" fill="none" stroke="{C}" stroke-width="2.5"/>',
           line(W / 2, 6, W / 2, H - 6, 2, 0.5)]
    for nm, x, y, t in players:
        X, Y = 6 + x * (W - 12), 6 + y * (H - 12)
        if t == "a":
            out.append(f'<circle cx="{X:.0f}" cy="{Y:.0f}" r="11" fill="{BLUE}" fill-opacity="0.35" stroke="{C}" stroke-width="2.5"/>')
        else:
            out.append(f'<rect x="{X - 10:.0f}" y="{Y - 10:.0f}" width="20" height="20" fill="{ORANGE}" fill-opacity="0.4" stroke="{C}" stroke-width="2.5"/>')
        out.append(text(X, Y + 5, nm, 13, weight="bold"))
    return svg(W, H, "".join(out))


