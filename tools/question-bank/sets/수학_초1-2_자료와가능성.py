def shapes(items, gap=10):
    """items: (모양, 색칠 여부, 크기 'L'|'S') — 색칠은 파랑 채움, 안 칠한 것은 빈 모양"""
    R = 16
    cs = 2 * R + gap
    out = []
    for i, (k, filled, size) in enumerate(items):
        r = R if size == "L" else 9
        cx = gap + R + i * cs
        out.append(shape(k, cx, R + 10 + (R - r) * 0.6, r, fill=BLUE if filled else "none"))
    return svg(len(items) * cs + gap, 2 * R + 20, "".join(out))


