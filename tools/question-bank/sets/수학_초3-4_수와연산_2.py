def rd(x):
    """소수를 읽는 방법: 3.45 → 삼 점 사오 (정수 부분은 숫자 하나로 읽는 경우만)"""
    whole, frac = f"{x}".split(".")
    return f"{DG[int(whole)]} 점 " + "".join(DG[int(c)] for c in frac)


def bar_unequal(widths, shaded=0, w=220, h=34):
    """똑같지 않게 나눈 막대 (분수가 아닌 예)"""
    tot = sum(widths)
    out = []
    x = 4
    for i, wd in enumerate(widths):
        cw = wd / tot * w
        fill = f'fill="{BLUE}" fill-opacity="0.45"' if i < shaded else 'fill="none"'
        out.append(f'<rect x="{_n(x)}" y="4" width="{_n(cw)}" height="{h}" {fill} stroke="{C}" stroke-width="2"/>')
        x += cw
    return svg(w + 8, h + 8, "".join(out))


def square_rows(n=3, shaded=1, a=90):
    """정사각형을 가로로 똑같이 n줄로 나누고 위에서 shaded줄을 색칠"""
    out = []
    hh = a / n
    for i in range(n):
        fill = f'fill="{BLUE}" fill-opacity="0.45"' if i < shaded else 'fill="none"'
        out.append(f'<rect x="4" y="{_n(4 + i * hh)}" width="{a}" height="{_n(hh)}" {fill} stroke="{C}" stroke-width="2"/>')
    return svg(a + 8, a + 8, "".join(out))


