def nl(lo, hi, marks=(), pts=()):
    """수직선. marks: {값: 라벨} 눈금 아래 표시, pts: [(값, 글자)] 점"""
    W, H = 330, 74
    pad = 22
    sc = (W - 2 * pad) / (hi - lo)
    X = lambda v: pad + (v - lo) * sc
    y = 46
    out = [line(pad - 8, y, W - pad + 8, y, 2.2)]
    for v in range(lo, hi + 1):
        out.append(line(X(v), y - 5, X(v), y + 5, 2))
        if v in dict(marks):
            out.append(text(X(v), y + 22, dict(marks)[v], 12, weight="bold"))
        else:
            out.append(text(X(v), y + 22, v, 12))
    for v, g in pts:
        out.append(f'<circle cx="{_n(X(v))}" cy="{y}" r="5" fill="{BLUE}"/>')
        out.append(text(X(v), y - 12, g, 13, weight="bold"))
    return svg(W, H, "".join(out))


