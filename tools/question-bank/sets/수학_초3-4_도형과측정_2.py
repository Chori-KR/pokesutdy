def tri_sides(c, a, bb, s=13):
    """밑변 c, 오른쪽 변 a, 왼쪽 변 b(cm) → 세 꼭짓점. P0→P1=c, P1→P2=a, P2→P0=b"""
    x = (bb * bb + c * c - a * a) / (2 * c)
    y = math.sqrt(max(bb * bb - x * x, 0.01))
    return [(0, y * s), (c * s, y * s), (x * s, 0)]


def tri_len(c, a, bb, s=13, name=None):
    P = tri_sides(c, a, bb, s)
    return tri_fig(P, side_txt={0: f"{c} cm", 1: f"{a} cm", 2: f"{bb} cm"}, pad=34)


def tri_row(items, cols=2):
    return hold([(tri_len(*t), LAB[i]) for i, t in enumerate(items)], gap=2, cols=cols)


def tri_plain(P, **kw):
    return tri_fig(P, pad=26, **kw)


def tri_angles(angs, name=None, s=1.0):
    """세 각(도)으로 삼각형을 그리고 각 꼭짓점 안쪽에 각도를 쓴다"""
    A, B_, C_ = angs
    base = 130
    # 밑변 P0P1, P0의 각 A, P1의 각 B
    ra, rb = math.radians(A), math.radians(B_)
    # 사인 법칙으로 꼭짓점 P2
    gamma = math.pi - ra - rb
    bside = base * math.sin(rb) / math.sin(gamma)      # P0P2
    P2 = (bside * math.cos(ra), -bside * math.sin(ra))
    P = [(0, 0), (base, 0), P2]
    ys = [p[1] for p in P]
    P = [(x, y - min(ys)) for x, y in P]
    return tri_fig(P, ang_txt={0: f"{A}°", 1: f"{B_}°", 2: f"{C_}°"}, pad=36, W=None, ang_out=True)


