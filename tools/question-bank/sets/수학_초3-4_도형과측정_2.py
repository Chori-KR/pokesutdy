def cells_shape(cells, g=24, label=None):
    return cell_grid({c: "B" for c in cells}, max(c for c, _ in cells) + 1, max(r for _, r in cells) + 1, g=g)


def L_hole():
    """빈 곳(점선)이 L자 3칸인 모양"""
    holes = [(1, 1), (2, 1), (2, 2)]
    cells = {(c, r): "B" for c in range(4) for r in range(3) if (c, r) not in holes}
    return cell_grid(cells, 4, 3, g=26, hole=holes)


def tiled_region():
    cells = {}
    for r in range(3):
        for c in range(4):
            cells[(c, r)] = "B"
    holes = [(1, 0), (2, 1), (0, 2), (3, 2)]
    for h in holes:
        del cells[h]
    return cell_grid(cells, 4, 3, g=28, hole=holes)


def two_right_tri():
    """똑같은 직각삼각형 2개를 빗변끼리 붙여 만든 모양"""
