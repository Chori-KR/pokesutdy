def unit_tape(n, u=34):
    """1 cm 칸이 n개인 색 테이프"""
    out = [text(10 + u / 2, 16, "1 cm", 13, weight="bold"),
           line(10, 22, 10 + u, 22, 2), line(10, 18, 10, 26, 2), line(10 + u, 18, 10 + u, 26, 2)]
    for k in range(n):
        out.append(f'<rect x="{10 + k * u}" y="32" width="{u}" height="28" fill="{BLUE}" fill-opacity="{0.6 if k == 0 else 0.3}" stroke="{C}" stroke-width="2"/>')
    return svg(n * u + 20, 68, "".join(out))


def spans(people, w=260):
    """같은 길이의 책상을 서로 다른 뼘으로 잰 모습: people=[(뼘 수, 이름)]"""
    out = []
    for i, (n, nm) in enumerate(people):
        y = 14 + i * 56
        out.append(text(44, y + 30, nm, 13, "end", "bold"))
        out.append(f'<rect x="54" y="{y + 26}" width="{w}" height="12" fill="{BLUE}" fill-opacity="0.35" stroke="{C}" stroke-width="2"/>')
        u = w / n
        for k in range(n):
            x = 54 + k * u
            out.append(f'<path d="M{_n(x)},{y + 24} Q{_n(x + u / 2)},{y - 2} {_n(x + u)},{y + 24}" fill="none" stroke="{ORANGE}" stroke-width="2.5"/>')
        out.append(text(54 + w + 6, y + 36, f"{n}뼘", 13, "start", "bold"))
    return svg(w + 100, 14 + len(people) * 56, "".join(out))


def ref_and_tape(n, u=30):
    """1 cm 길이만 보여 주고 눈금 없는 테이프의 길이 어림"""
    out = [text(10, 18, "1 cm", 13, "start", "bold"),
           f'<rect x="54" y="6" width="{u}" height="16" fill="{ORANGE}" fill-opacity="0.6" stroke="{C}" stroke-width="2"/>',
           f'<rect x="10" y="40" width="{_n(n * u)}" height="26" fill="{BLUE}" fill-opacity="0.45" stroke="{C}" stroke-width="2"/>']
    return svg(n * u + 24, 74, "".join(out))


def stick_and_rope(n_m, u=70):
    out = [text(10, 22, "1 m", 13, "start", "bold"),
           f'<rect x="46" y="10" width="{u}" height="16" fill="{ORANGE}" fill-opacity="0.6" stroke="{C}" stroke-width="2"/>',
           f'<path d="M10,52 C{_n(n_m * u * 0.3)},40 {_n(n_m * u * 0.6)},64 {_n(n_m * u + 10)},52" fill="none" stroke="{BLUE}" stroke-width="5"/>',
           text(n_m * u / 2, 82, "줄넘기 줄", 13, weight="bold")]
    return svg(n_m * u + 24, 90, "".join(out))


