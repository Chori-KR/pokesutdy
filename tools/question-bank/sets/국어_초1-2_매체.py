ST = f'stroke="{C}" stroke-width="2.5" stroke-linejoin="round"'


def rainy():
    """비 오는 날 우산을 쓴 아이"""
    o = [f'<path d="M40,70 Q100,-14 160,70 Z" fill="{BLUE}" fill-opacity="0.5" {ST}/>',
         line(100, 70, 100, 118, 3)]
    for x, y in [(26, 30), (52, 50), (156, 44), (178, 66), (22, 90), (176, 104)]:
        o.append(line(x, y, x - 5, y + 14, 2.5, color=BLUE))
    o.append(f'<circle cx="100" cy="132" r="11" fill="none" {ST}/>' + line(100, 143, 100, 178, 2.5)
             + line(100, 152, 88, 164, 2.5) + line(100, 152, 108, 120, 2.5)
             + line(100, 178, 90, 202, 2.5) + line(100, 178, 110, 202, 2.5))
    return svg(200, 210, "".join(o))


def phone():
    """스마트폰 화면의 문자 메시지"""
    o = [f'<rect x="40" y="6" width="150" height="190" rx="18" fill="none" {ST}/>',
         f'<rect x="54" y="26" width="122" height="146" rx="6" fill="none" stroke="{C}" stroke-width="2"/>',
         f'<rect x="60" y="36" width="110" height="56" rx="10" fill="{BLUE}" fill-opacity="0.3" {ST}/>',
         text(115, 58, "내일 소풍이에요.", 12), text(115, 78, "도시락을 챙겨요!", 12),
         f'<rect x="60" y="104" width="80" height="34" rx="10" fill="{ORANGE}" fill-opacity="0.35" {ST}/>',
         text(100, 126, "알겠어요!", 13),
         f'<circle cx="115" cy="186" r="5" fill="none" stroke="{C}" stroke-width="2"/>']
    return svg(230, 204, "".join(o))


