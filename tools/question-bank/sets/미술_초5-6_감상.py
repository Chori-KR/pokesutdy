def chip(col, op, label, w=64, h=52):
    """색 면 + 색 이름(색만으로 구분하지 않도록 글자를 함께 씀)"""
    return svg(w, h, f'<rect x="3" y="3" width="{w - 6}" height="{h - 6}" rx="4" fill="{col}" fill-opacity="{op}" stroke="{C}" stroke-width="2.5"/>'
               + text(w / 2, h / 2 + 5, label, 14, weight="bold"))

