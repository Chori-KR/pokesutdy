def candle_jars():
    """(가) 촛불만 (나) 집기병으로 완전히 덮음 (다) 집기병 아래에 나무토막을 괴어 틈을 둠"""
    out = []
    for i, (x, kind) in enumerate(((45, "a"), (155, "b"), (265, "c"))):
        out.append(line(x - 34, 120, x + 34, 120, 3))
        out.append(f'<rect x="{x - 6}" y="92" width="12" height="28" fill="none" stroke="{C}" stroke-width="2.5"/>')
        out.append(f'<ellipse cx="{x}" cy="80" rx="5" ry="10" fill="{ORANGE}" fill-opacity="0.85" stroke="{C}" stroke-width="2"/>')
        if kind == "b":
            out.append(f'<path d="M{x - 24},120 L{x - 24},46 Q{x},34 {x + 24},46 L{x + 24},120" fill="none" stroke="{C}" stroke-width="2.5"/>')
        if kind == "c":
            out.append(f'<path d="M{x - 24},112 L{x - 24},46 Q{x},34 {x + 24},46 L{x + 24},112" fill="none" stroke="{C}" stroke-width="2.5"/>')
            out.append(f'<rect x="{x - 30}" y="112" width="10" height="8" fill="{BLUE}" fill-opacity="0.4" stroke="{C}" stroke-width="2"/>')
            out.append(f'<rect x="{x + 20}" y="112" width="10" height="8" fill="{BLUE}" fill-opacity="0.4" stroke="{C}" stroke-width="2"/>')
        out.append(text(x, 146, "(" + "가나다"[i] + ")", 14, weight="bold"))
    return svg(310, 156, "".join(out))


