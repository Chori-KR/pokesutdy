def A(n, u="°"):
    """단답형 허용 답: 숫자만/단위 붙임"""
    return [str(n), f"{n}{u}", f"{n} {u}"]


def mc(b, S, lv, body, ok, bad, why, svg=None, keep=False):
    kw = dict(options=[ok] + list(bad), answer=ok, why=why, keep=keep)
    if svg:
        kw["svg"] = svg
    b.q(S, lv, body, **kw)


def sh(b, S, lv, body, answers, why, svg=None):
    kw = dict(answers=answers, why=why)
    if svg:
        kw["svg"] = svg
