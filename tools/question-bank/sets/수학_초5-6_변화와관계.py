def two_dots(a, c, per_row=7, labels=("원", "네모")):
    """파랑 동그라미 a개와 주황 네모 c개"""
    out = []
    r = 9
    x = 12
    for i in range(a):
        out.append(f'<circle cx="{x + (i % per_row) * 26}" cy="{18 + (i // per_row) * 26}" r="{r}" fill="{BLUE}" fill-opacity="0.6" stroke="{C}" stroke-width="2"/>')
    ya = 18 + ((a - 1) // per_row + 1) * 26 + 6
    for i in range(c):
        out.append(f'<rect x="{x - r + (i % per_row) * 26}" y="{ya - r + (i // per_row) * 26}" width="{2 * r}" height="{2 * r}" fill="{ORANGE}" fill-opacity="0.6" stroke="{C}" stroke-width="2"/>')
    H = ya + ((c - 1) // per_row + 1) * 26
    return svg(per_row * 26 + 16, H, "".join(out))


