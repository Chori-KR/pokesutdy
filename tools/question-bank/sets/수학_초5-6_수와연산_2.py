Fr = Fraction


def F(x):
    """Fraction -> 분수(또는 대분수) 수식"""
    x = Fr(x)
    if x.denominator == 1:
        return f"${x.numerator}$"
    if x.numerator > x.denominator:
        w, r = divmod(x.numerator, x.denominator)
        return f"${w}\\frac{{{r}}}{{{x.denominator}}}$"
    return f"$\\frac{{{x.numerator}}}{{{x.denominator}}}$"


def Fi(x):
    """가분수 그대로"""
    x = Fr(x)
    return f"$\\frac{{{x.numerator}}}{{{x.denominator}}}$"


def sa(x):
    """단답형 답: 분수 문자열 변형"""
    x = Fr(x)
    a = [f"{x.numerator}/{x.denominator}", f"{x.numerator} / {x.denominator}"]
    if x.numerator > x.denominator:
        w, r = divmod(x.numerator, x.denominator)
        if r:
            a += [f"{w} {r}/{x.denominator}", f"{w}과 {r}/{x.denominator}"]
    if x.denominator == 1:
        a = [str(x.numerator)]
    return a


def ops(correct, *wrong, f=F):
    """보기: 정답과 오답 Fraction들"""
    return [f(correct)] + [f(w) for w in wrong]


