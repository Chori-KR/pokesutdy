def latlon_grid(lat, lon, W=300, H=190):
    """북위 0~60, 동경 0~90 격자 위에 한 점. lat 북위, lon 동경"""
    x0, y0, x1, y1 = 44, 14, W - 14, H - 34
    out = [f'<rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}" fill="none" stroke="{C}" stroke-width="2"/>']
    for i, la in enumerate((0, 20, 40, 60)):
        y = y1 - (y1 - y0) * la / 60
        out.append(line(x0, y, x1, y, 2, op=0.45))
        out.append(text(x0 - 8, y + 4, f"{la}°", 12, anchor="end"))
    for lo in (0, 30, 60, 90):
        x = x0 + (x1 - x0) * lo / 90
        out.append(line(x, y0, x, y1, 2, op=0.45))
        out.append(text(x, y1 + 18, f"{lo}°", 12))
    out.append(text(14, y0 + (y1 - y0) / 2 + 4, "북위", 12))
    out.append(text(x0 + (x1 - x0) / 2, H - 4, "동경", 12))
    px = x0 + (x1 - x0) * lon / 90
    py = y1 - (y1 - y0) * lat / 60
    out.append(f'<circle cx="{px:.1f}" cy="{py:.1f}" r="6" fill="{ORANGE}" stroke="{C}" stroke-width="2"/>')
    out.append(text(px + 12, py - 8, "가", 14, anchor="start", weight="bold"))
    return svg(W, H, "".join(out))


