def straws(items):
    """길이가 다른 빨대 피리: items [(이름, 길이)]"""
    out = []
    for i, (name, ln) in enumerate(items):
        y = 14 + i * 34
        out.append(f'<rect x="40" y="{y}" width="{ln}" height="14" rx="3" fill="{BLUE}" fill-opacity="0.3" stroke="{C}" stroke-width="2.5"/>')
        out.append(text(20, y + 12, name, 13, weight="bold"))
    return svg(260, 14 + len(items) * 34, "".join(out))


