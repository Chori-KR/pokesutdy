def circ_segs():
    """원 안의 선분 세 개: 지름 ㄱㄴ, 현 ㄷㄹ, 반지름 ㅇㅁ"""
    r = 70
    cx = cy = r + 24
    def P(a):
        return cx + r * math.cos(math.radians(a)), cy - r * math.sin(math.radians(a))
    out = [f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{C}" stroke-width="3"/>']
    pa, pb = P(200), P(20)
    out.append(line(*pa, *pb, 3, color=ORANGE) + dot(*pa) + dot(*pb))
    out.append(text(pa[0] - 12, pa[1] + 6, "ㄱ", 14, weight="bold") + text(pb[0] + 12, pb[1] - 2, "ㄴ", 14, weight="bold"))
    pc, pd = P(80), P(150)
    out.append(line(*pc, *pd, 3) + dot(*pc) + dot(*pd))
    out.append(text(pc[0] + 4, pc[1] - 10, "ㄷ", 14, weight="bold") + text(pd[0] - 14, pd[1] - 4, "ㄹ", 14, weight="bold"))
    pm = P(-60)
    out.append(line(cx, cy, *pm, 3, None, "6 4") + dot(*pm) + text(pm[0] + 12, pm[1] + 6, "ㅁ", 14, weight="bold"))
    out.append(dot(cx, cy, 4.5) + text(cx - 8, cy - 10, "ㅇ", 14, weight="bold"))
    return svg(2 * r + 48, 2 * r + 48, "".join(out))


def three_circles(d=70, label="10 cm"):
    r = d / 2
    out = []
    for i in range(3):
        cx = 16 + r + i * d
        out.append(f'<circle cx="{_n(cx)}" cy="{r + 16}" r="{_n(r)}" fill="none" stroke="{C}" stroke-width="3"/>')
        out.append(line(cx - r, r + 16, cx + r, r + 16, 2.5, None, "5 4", color=ORANGE))
    out.append(text(16 + r, r + 8, label, 13, weight="bold"))
    return svg(32 + 3 * d, d + 32, "".join(out))


def concentric(ra=40, rb=80):
    cx = cy = rb + 16
    out = [f'<circle cx="{cx}" cy="{cy}" r="{rb}" fill="none" stroke="{C}" stroke-width="3"/>',
           f'<circle cx="{cx}" cy="{cy}" r="{ra}" fill="none" stroke="{BLUE}" stroke-width="3"/>',
           line(cx, cy, cx - ra, cy, 2.5, BLUE, "5 4"), line(cx, cy, cx, cy + rb, 2.5, None, "5 4"), dot(cx, cy, 4.5),
           text(cx - ra / 2, cy - 8, "2 cm", 13, weight="bold"), text(cx + 24, cy + rb * 0.75, "4 cm", 13, weight="bold")]
    return svg(2 * rb + 32, 2 * rb + 32, "".join(out))


